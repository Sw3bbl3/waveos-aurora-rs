//! arm64 Linux's system call table: the generic one (Linux's
//! `include/uapi/asm-generic/unistd.h`), which has none of the old calls
//! (`open`, `stat`, `fork`, `pipe`, `poll`, `select`, `dup2`, `rename`,
//! `mkdir`…): programs use `openat`, `newfstatat`, `clone`, `pipe2`,
//! `ppoll`, `pselect6`, `dup3`, `renameat2`, `mkdirat` and so on, which
//! the layer implements in full for x86-64 programs already.
//!
//! Every arm64 call has an x86-64 call of the same name. Most have the same
//! arguments and memory, so they are [`Map::Same`]; `clone` takes its last
//! two arguments the other way round (`tls` before `child_tid`) and is
//! [`Map::Own`]. Calls whose structures differ (`fstat`/`newfstatat`'s
//! `struct stat`, the `epoll` calls' `struct epoll_event`, `rt_sigreturn`'s
//! frame) are the same calls: the layer lays those structures out for the
//! architecture it runs on. A call the x86-64 layer doesn't provide is
//! `ENOSYS` here too.
//!
//! The numbers are checked against Linux 6.1's headers by the host tests
//! (`tests/headers.rs`), and so is every x86-64 number the table names.

