#!/usr/bin/env python3
"""Generates tests/data/vectors.rs: WPA2 and CCMP test data from an independent
implementation (Python's hashlib/hmac and the `cryptography` package), so
the Rust code is checked against something it shares no code with.

    python3 libs/wifi/tests/make_vectors.py > libs/wifi/tests/data/vectors.rs
"""
import hashlib
import hmac
import struct

from cryptography.hazmat.primitives.ciphers.aead import AESCCM
from cryptography.hazmat.primitives.keywrap import aes_key_wrap


def prf(key, label, data, n):
    out = b""
    i = 0
    while len(out) < n:
        out += hmac.new(key, label + b"\0" + data + bytes([i]), hashlib.sha1).digest()
        i += 1
    return out[:n]


def mic(kck, frame):
    return hmac.new(kck, frame, hashlib.sha1).digest()[:16]


def key_frame(info, replay, nonce, data, key_len=0, rsc=0, kck=None):
    body = 95 + len(data)
    f = bytearray(struct.pack(">BBHB", 1, 3, body, 2))
    f += struct.pack(">HH", info, key_len)
    f += struct.pack(">Q", replay) + nonce + bytes(16) + struct.pack("<Q", rsc) + bytes(8) + bytes(16)
    f += struct.pack(">H", len(data)) + data
    if kck:
        f[81:97] = mic(kck, bytes(f))
    return bytes(f)


def rust(name, b):
    return f"pub const {name}: &[u8] = &[{', '.join(f'0x{x:02x}' for x in b)}];"


def pad(d):
    """Key data padding: 0xDD then zeros, to a multiple of 8 bytes."""
    if len(d) % 8:
        d += b"\xdd"
        d += bytes(-len(d) % 8)
    return d


ssid = b"WaveOS Test"
passphrase = b"correct horse battery"
pmk = hashlib.pbkdf2_hmac("sha1", passphrase, ssid, 4096, 32)
aa = bytes.fromhex("020000a0b0c0")
spa = bytes.fromhex("02005e10ab01")
anonce = bytes(range(32))
snonce = bytes(range(100, 132))

ptk = prf(pmk, b"Pairwise key expansion", min(aa, spa) + max(aa, spa) + min(anonce, snonce) + max(anonce, snonce), 48)
kck, kek, tk = ptk[:16], ptk[16:32], ptk[32:]

oui = bytes([0x00, 0x0F, 0xAC])
ap_ie = bytes([48, 20, 1, 0]) + oui + b"\x04" + b"\x01\x00" + oui + b"\x04" + b"\x01\x00" + oui + b"\x02" + b"\x00\x00"
sta_ie = ap_ie  # the station asks for the same: CCMP/CCMP/PSK
gtk = bytes(range(200, 216))

V2 = 2
PAIRWISE, INSTALL, ACK, MIC, SECURE, ENCRYPTED = 0x8, 0x40, 0x80, 0x100, 0x200, 0x1000

msg1 = key_frame(V2 | PAIRWISE | ACK, 1, anonce, b"", key_len=16)
msg2 = key_frame(V2 | PAIRWISE | MIC, 1, snonce, sta_ie, kck=kck)
gtk_kde = bytes([0xDD, 6 + 16]) + oui + b"\x01" + bytes([1, 0]) + gtk
key_data = pad(ap_ie + gtk_kde)
wrapped = aes_key_wrap(kek, key_data)
msg3 = key_frame(V2 | PAIRWISE | INSTALL | ACK | MIC | SECURE | ENCRYPTED, 2, anonce, wrapped, key_len=16, rsc=5, kck=kck)
msg4 = key_frame(V2 | PAIRWISE | MIC | SECURE, 2, bytes(32), b"", kck=kck)
# Message 3 as an attacker without the password would send it: the MIC is wrong.
bad_kck = bytes(16)
msg3_forged = key_frame(V2 | PAIRWISE | INSTALL | ACK | MIC | SECURE | ENCRYPTED, 2, anonce, wrapped, key_len=16, rsc=5, kck=bad_kck)

gtk2 = bytes(range(50, 66))
g_data = pad(bytes([0xDD, 22]) + oui + b"\x01" + bytes([2, 0]) + gtk2)
group1 = key_frame(V2 | ACK | MIC | SECURE | ENCRYPTED, 3, bytes(32), aes_key_wrap(kek, g_data), key_len=16, rsc=9, kck=kck)
group2 = key_frame(V2 | MIC | SECURE, 3, bytes(32), b"", kck=kck)

# CCMP: a QoS data frame (TID 5) from the station, PN 0x0102030405.
hdr = bytearray()
hdr += bytes([0x88, 0x01])  # QoS data, ToDS
hdr += bytes([0, 0]) + aa + spa + bytes.fromhex("ffffffffffff")
hdr += struct.pack("<H", 0x123 << 4 | 0)  # sequence 0x123, fragment 0
hdr += bytes([5, 0])  # QoS control: TID 5
plain = bytes.fromhex("aaaa030000000800") + b"hello, wireless world"
pn = 0x0102030405
nonce = bytes([5]) + spa + pn.to_bytes(6, "big")
aad = bytes([0x88, 0x41]) + aa + spa + bytes.fromhex("ffffffffffff") + bytes([0, 0]) + bytes([5, 0])
ct = AESCCM(tk, tag_length=8).encrypt(nonce, plain, aad)
ccmp_hdr = bytes([pn & 0xFF, (pn >> 8) & 0xFF, 0, 0x20, (pn >> 16) & 0xFF, (pn >> 24) & 0xFF, (pn >> 32) & 0xFF, (pn >> 40) & 0xFF])
protected = bytes([hdr[0], hdr[1] | 0x40]) + bytes(hdr[2:]) + ccmp_hdr + ct

print("// Generated by make_vectors.py (Python hashlib/hmac + cryptography). Do not edit.")
print(f'pub const SSID: &[u8] = b"{ssid.decode()}";')
print(f'pub const PASSPHRASE: &[u8] = b"{passphrase.decode()}";')
for name, b in [
    ("PMK", pmk), ("AA", aa), ("SPA", spa), ("ANONCE", anonce), ("SNONCE", snonce),
    ("KCK", kck), ("KEK", kek), ("TK", tk), ("AP_IE", ap_ie), ("STA_IE", sta_ie), ("GTK", gtk), ("GTK2", gtk2),
    ("MSG1", msg1), ("MSG2", msg2), ("MSG3", msg3), ("MSG3_FORGED", msg3_forged), ("MSG4", msg4),
    ("GROUP1", group1), ("GROUP2", group2),
    ("CCMP_PLAIN_FRAME", bytes(hdr) + plain), ("CCMP_PROTECTED_FRAME", protected),
]:
    print(rust(name, b))
print(f"pub const CCMP_PN: u64 = {pn:#x};")
