"""Generates linux-programs/wl-bridge/src/protocol.rs from the Wayland
protocol XML files in linux-programs/wl-bridge/protocols (from Debian's
libwayland-dev 1.21 and wayland-protocols 1.31).

    python3 tools/wayland_protocol.py
"""
import os
import xml.etree.ElementTree as ET

ROOT = os.path.join(os.path.dirname(__file__), "..", "linux-programs", "wl-bridge")
FILES = ["wayland.xml", "xdg-shell.xml", "xdg-decoration-unstable-v1.xml", "viewporter.xml"]
CODES = {"int": "i", "uint": "u", "fixed": "f", "string": "s", "object": "o", "new_id": "n", "array": "a", "fd": "h"}


def sig(msg):
    out = ""
    for a in msg.findall("arg"):
        t = a.get("type")
        if t == "new_id" and a.get("interface") is None:
            out += "sun"  # interface name, version, id (wl_registry.bind)
            continue
        if a.get("allow-null") == "true":
            out += "?"
        out += CODES[t]
    return out


def ident(name):
    return name.upper()


lines = [
    "//! Wayland interfaces, generated by `tools/wayland_protocol.py` from the",
    "//! protocol XML in `protocols/`. Each interface lists its requests'",
    "//! argument signatures (i int, u uint, f fixed, s string, o object,",
    "//! n new id, a array, h file descriptor; ? allows null) and the opcodes",
    "//! of its requests and events.",
    "",
    "#![allow(dead_code)]",
    "",
]
names = []
for f in FILES:
    tree = ET.parse(os.path.join(ROOT, "protocols", f))
    for iface in tree.getroot().findall("interface"):
        name = iface.get("name")
        names.append(name)
        lines.append(f"pub mod {name} {{")
        lines.append(f'    pub const NAME: &str = "{name}";')
        lines.append(f"    pub const VERSION: u32 = {iface.get('version')};")
        reqs = iface.findall("request")
        sigs = ", ".join(f'"{sig(r)}"' for r in reqs)
        lines.append(f"    pub const REQUESTS: &[&str] = &[{sigs}];")
        for kind, tag in (("req", "request"), ("ev", "event")):
            msgs = iface.findall(tag)
            if msgs:
                lines.append(f"    pub mod {kind} {{")
                for i, m in enumerate(msgs):
                    lines.append(f"        pub const {ident(m.get('name'))}: u16 = {i};")
                lines.append("    }")
        lines.append("}")
        lines.append("")
lines.append("/// The request signatures of interface `name`.")
lines.append("pub fn requests(name: &str) -> &'static [&'static str] {")
lines.append("    match name {")
for n in names:
    lines.append(f"        {n}::NAME => {n}::REQUESTS,")
lines.append("        _ => &[],")
lines.append("    }")
lines.append("}")
open(os.path.join(ROOT, "src", "protocol.rs"), "w").write("\n".join(lines) + "\n")
print(len(names), "interfaces")
