//! libdrm's `modetest`, for `/System/Linux/bin/modetest`: the KMS test
//! program every Linux display driver is tried with, built unmodified from
//! libdrm's release (MIT) with the library itself, static with musl, so the
//! kernel self-tests can run it against `/dev/dri/card0`.
//!
//! libdrm's build (meson) makes `config.h` and one generated table; both
//! are made here. musl has no kernel headers, so `<linux/types.h>` and
//! `<asm/ioctl.h>`, which libdrm's `drm.h` includes, are two small stand-ins.

use super::linux::{fetch, Cc};
use super::{root, Program};
use std::ffi::{OsStr, OsString};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

const LIBDRM: (&str, &str) = (
    "https://snapshot.debian.org/archive/debian/20261001T000000Z/pool/main/libd/libdrm/libdrm_2.4.114.orig.tar.xz",
    "3049cf843a47d12e5eeefbc3be3496d782fa09f42346bf0b7defe3d1e598d026",
);

/// The library and the test program's sources.
const SOURCES: &[&str] = &[
    "xf86drm.c",
    "xf86drmHash.c",
    "xf86drmRandom.c",
    "xf86drmSL.c",
    "xf86drmMode.c",
    "tests/util/format.c",
    "tests/util/kms.c",
    "tests/util/pattern.c",
    "tests/modetest/buffers.c",
    "tests/modetest/cursor.c",
    "tests/modetest/modetest.c",
];

