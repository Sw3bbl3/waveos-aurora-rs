/// `generated_static_table_fourcc.h`, as libdrm's `gen_table_fourcc.py`
/// writes it from `drm_fourcc.h`: the modifiers and vendors by name.
fn fourcc_table(header: &str) -> String {
    let defines = |prefix: &str| -> Vec<String> {
        header
            .lines()
            .filter_map(|l| l.strip_prefix("#define ")?.strip_prefix(prefix))
            .map(|rest| rest.chars().take_while(|c| c.is_ascii_alphanumeric() || *c == '_').collect::<String>())
            .filter(|name| !name.is_empty())
            .collect()
    };
    let mut out = String::from(
        "/* AUTOMATICALLY GENERATED by gen_table_fourcc.py. You should modify\n   that script instead of adding here entries manually! */\nstatic const struct drmFormatModifierInfo drm_format_modifier_table[] = {\n    { DRM_MODIFIER_INVALID(NONE, INVALID) },\n    { DRM_MODIFIER_LINEAR(NONE, LINEAR) },\n",
    );
    for m in defines("I915_FORMAT_MOD_") {
        out.push_str(&format!("    {{ DRM_MODIFIER_INTEL({m}, {m}) }},\n"));
    }
    // Vendors' own modifiers: those followed by whitespace in the header.
    let vendors = ["ARM", "SAMSUNG", "QCOM", "VIVANTE", "NVIDIA", "BROADCOM", "ALLWINNER"];
    for l in header.lines() {
        let Some(rest) = l.strip_prefix("#define DRM_FORMAT_MOD_") else { continue };
        let name: String = rest.chars().take_while(|c| c.is_ascii_alphanumeric() || *c == '_').collect();
        let followed_by_space = rest[name.len()..].starts_with(char::is_whitespace);
        let Some((vendor, m)) = name.split_once('_') else { continue };
        if !followed_by_space || !vendors.contains(&vendor) || !name.starts_with(vendor) {
            continue;
        }
        if vendor == "ARM" && matches!(m, "TYPE_AFBC" | "TYPE_MISC" | "TYPE_AFRC") {
            continue;
        }
        out.push_str(&format!("    {{ DRM_MODIFIER({vendor}, {m}, {m}) }},\n"));
    }
    out.push_str("};\nstatic const struct drmFormatModifierVendorInfo drm_format_modifier_vendor_table[] = {\n");
    for v in defines("DRM_FORMAT_MOD_VENDOR_") {
        out.push_str(&format!("    {{ DRM_FORMAT_MOD_VENDOR_{v}, \"{v}\" }},\n"));
    }
    out.push_str("};\n");
    out
}

/// `modetest` and libdrm's license, or nothing (with a warning) if the
/// source can't be fetched.
pub fn build(cc: &Cc) -> Vec<Program> {
    let Some(archive) = fetch(LIBDRM.0, LIBDRM.1) else {
        eprintln!("warning: libdrm's source could not be downloaded: modetest is left out of the image");
        return Vec::new();
    };
    let work = root().join("target/linux/libdrm");
    let src = work.join("libdrm-2.4.114");
    if !src.join("xf86drm.c").exists() {
        let _ = fs::remove_dir_all(&work);
        fs::create_dir_all(&work).unwrap();
        let ok = Command::new("tar").arg("-xf").arg(&archive).arg("-C").arg(&work).status();
        assert!(ok.is_ok_and(|s| s.success()), "could not unpack {}", archive.display());
    }
    let gen = work.join("gen");
    fs::create_dir_all(gen.join("linux")).unwrap();
    fs::create_dir_all(gen.join("asm")).unwrap();
    let write = |p: PathBuf, text: &str| {
        if fs::read_to_string(&p).ok().as_deref() != Some(text) {
            fs::write(p, text).unwrap();
        }
    };
    write(gen.join("config.h"), CONFIG_H);
    write(gen.join("linux/types.h"), LINUX_TYPES_H);
    write(gen.join("asm/ioctl.h"), ASM_IOCTL_H);
    let fourcc = fs::read_to_string(src.join("include/drm/drm_fourcc.h")).expect("drm_fourcc.h");
    write(gen.join("generated_static_table_fourcc.h"), &fourcc_table(&fourcc));

    let exe = root().join("target/linux/modetest");
    if !exe.exists() {
        let inc = |p: &Path| OsString::from(format!("-I{}", p.display()));
        let flags: Vec<OsString> = [
            OsString::from("-w"),
            OsString::from("-include"),
            gen.join("config.h").into_os_string(),
            inc(&gen),
            inc(&src),
            inc(&src.join("include/drm")),
            inc(&src.join("tests")),
            inc(&src.join("tests/util")),
        ]
        .into_iter()
        .collect();
        let flags: Vec<&OsStr> = flags.iter().map(OsString::as_os_str).collect();
        let objs_dir = work.join("obj");
        fs::create_dir_all(&objs_dir).unwrap();
        let mut objs = Vec::new();
        for s in SOURCES {
            let obj = objs_dir.join(Path::new(s).file_stem().unwrap()).with_extension("o");
            assert!(cc.compile(&src.join(s), &obj, &flags), "could not compile libdrm's {s}");
            objs.push(obj);
        }
        assert!(cc.link(&exe, &objs), "could not link modetest");
    }
    // The MIT notice, from the library's main file.
    let notice: String = fs::read_to_string(src.join("xf86drm.c"))
        .unwrap_or_default()
        .lines()
        .skip_while(|l| !l.contains("Copyright"))
        .take_while(|l| !l.trim_start().starts_with("*/"))
        .map(|l| l.trim_start().trim_start_matches('*').trim_start())
        .collect::<Vec<_>>()
        .join("\n");
    let license = work.join("LICENSE.txt");
    write(license.clone(), &format!("libdrm 2.4.114 (modetest)\n\n{notice}\n"));
    vec![(String::from("Linux/bin/modetest"), exe), (String::from("Licenses/libdrm.txt"), license)]
}
